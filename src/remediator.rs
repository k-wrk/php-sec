use crate::ssh::RemoteClient;
use anyhow::{anyhow, Result};

pub struct Remediator;

impl Remediator {
    /// Upgrades PHP packages safely using apt-get
    pub fn upgrade_php_packages(client: &RemoteClient) -> Result<String> {
        let cmd = "DEBIAN_FRONTEND=noninteractive apt-get update && \
                   DEBIAN_FRONTEND=noninteractive apt-get --only-upgrade install -y 'php*-fpm' 'php*-cli' 'php*-common'";
        let (code, stdout, stderr) = client.execute(cmd)?;
        if code != 0 {
            return Err(anyhow!("Failed to upgrade PHP packages: {}", stderr));
        }
        Ok(stdout)
    }

    /// Injects a dedicated conf.d file with security hardening directives for PHP-FPM
    pub fn apply_php_hardening(client: &RemoteClient, php_major_minor: &str) -> Result<String> {
        let conf_content = r#"; Security hardening automatically generated by php-sec
expose_php = Off
display_errors = Off
display_startup_errors = Off
log_errors = On
allow_url_include = Off
session.cookie_httponly = 1
session.use_only_cookies = 1
"#;

        // Apply to both fpm/conf.d and cli/conf.d, as well as mods-available
        let mods_path = format!("/etc/php/{}/mods-available/security-hardening.ini", php_major_minor);
        let fpm_conf_path = format!("/etc/php/{}/fpm/conf.d/99-security-hardening.ini", php_major_minor);
        let cli_conf_path = format!("/etc/php/{}/cli/conf.d/99-security-hardening.ini", php_major_minor);

        let escaped_content = conf_content.trim();
        let cmd = format!(
            "mkdir -p /etc/php/{}/fpm/conf.d /etc/php/{}/cli/conf.d /etc/php/{}/mods-available 2>/dev/null && \
             cat << 'EOF' | tee {} {} {} > /dev/null\n{}\nEOF",
            php_major_minor, php_major_minor, php_major_minor,
            mods_path, fpm_conf_path, cli_conf_path,
            escaped_content
        );

        let (code, _, stderr) = client.execute(&cmd)?;
        if code != 0 {
            return Err(anyhow!("Failed to write security-hardening.ini: {}", stderr));
        }

        // Test PHP-FPM configuration syntax (if binary exists)
        let fpm_bin = format!("php-fpm{}", php_major_minor);
        let (bin_exists, _, _) = client.execute(&format!("which {} 2>/dev/null", fpm_bin))?;
        if bin_exists == 0 {
            let (test_code, _, test_err) = client.execute(&format!("{} -t", fpm_bin))?;
            if test_code != 0 {
                let _ = client.execute(&format!("rm -f {} {} {}", mods_path, fpm_conf_path, cli_conf_path));
                return Err(anyhow!("Invalid PHP-FPM syntax detected! Rollback performed: {}", test_err));
            }
        }

        Ok(format!("Hardening successfully applied for PHP {}", php_major_minor))
    }

    /// Injects 'server_tokens off;' into nginx.conf if not already present
    pub fn apply_nginx_hardening(client: &RemoteClient) -> Result<String> {
        // 1. Create timestamped backup of nginx.conf
        let backup_cmd = "cp /etc/nginx/nginx.conf /etc/nginx/nginx.conf.bak_php_sec_$(date +%s)";
        client.execute(backup_cmd)?;

        // 2. Inject into http { block if missing
        let inject_cmd = r#"grep -q "server_tokens off;" /etc/nginx/nginx.conf || sed -i '/http {/a \	server_tokens off;' /etc/nginx/nginx.conf"#;
        let (code, _, stderr) = client.execute(inject_cmd)?;
        if code != 0 {
            return Err(anyhow!("Failed to modify nginx.conf: {}", stderr));
        }

        // 3. Test Nginx syntax
        let (nginx_test, _, test_err) = client.execute("nginx -t")?;
        if nginx_test != 0 {
            // Restore latest backup on failure
            let _ = client.execute("cp $(ls -t /etc/nginx/nginx.conf.bak_php_sec_* | head -n 1) /etc/nginx/nginx.conf");
            return Err(anyhow!("nginx -t syntax check failed! Rollback performed: {}", test_err));
        }

        Ok("Nginx configured with 'server_tokens off;' successfully".into())
    }

    /// Restarts PHP-FPM and reloads Nginx safely
    pub fn restart_services(client: &RemoteClient, fpm_service: &str) -> Result<()> {
        // Syntax validation prior to restarting
        let (nginx_test, _, nginx_err) = client.execute("nginx -t")?;
        if nginx_test != 0 {
            let details = if !nginx_err.trim().is_empty() { nginx_err.trim() } else { "check syntax error" };
            return Err(anyhow!("nginx -t syntax check failed: {}", details));
        }

        // Clean service unit name if .service is missing/present
        let unit = if fpm_service.ends_with(".service") {
            fpm_service.to_string()
        } else {
            format!("{}.service", fpm_service)
        };

        // If unit is masked, unmask it before restarting
        let _ = client.execute(&format!("systemctl unmask {}", unit));

        // Restart PHP-FPM
        let fpm_cmd = format!("systemctl restart {}", unit);
        let (code_fpm, _, fpm_err) = client.execute(&fpm_cmd)?;
        if code_fpm != 0 {
            // Fetch journalctl logs for precise error reason
            let (_, journal_err, _) = client.execute(&format!("journalctl -u {} -n 5 --no-pager 2>/dev/null", unit))?;
            let details = if !journal_err.trim().is_empty() {
                journal_err.trim().lines().last().unwrap_or(fpm_err.trim())
            } else if !fpm_err.trim().is_empty() {
                fpm_err.trim()
            } else {
                "service failed to start"
            };
            return Err(anyhow!("systemctl restart {} failed: {}", unit, details));
        }

        // Reload Nginx
        let (code_nginx, _, nginx_reload_err) = client.execute("systemctl reload nginx")?;
        if code_nginx != 0 {
            let details = if !nginx_reload_err.trim().is_empty() { nginx_reload_err.trim() } else { "reload error" };
            return Err(anyhow!("systemctl reload nginx failed: {}", details));
        }

        Ok(())
    }
}
